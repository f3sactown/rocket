#!/usr/bin/env python3
"""Download the PAX roster from the "F3 SacTown Data" Google Sheet into data/roster.js.

Usage:  python3 tools/fetch_roster.py [--csv downloaded.csv] [--out data/roster.js]

The sheet is shared as "anyone with the link can view", so the CSV export of its
"Roster" tab downloads without signing in. The names in its "F3 Name" column are
written to data/roster.js; the app adds any it hasn't added before to each
device's PAX roster for quick-tap attendance (names a user removed stay removed).
Pass --csv to read a CSV you downloaded yourself (File > Download > CSV).

It exits with an error (and writes nothing) if the column is missing or the name
count looks wrong, so a scheduled run never commits a broken roster.
"""
import argparse
import csv
import io
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHEET_ID = "1_R4F0syR4m7eBen4j92PJCFeGrxEvNrbrL7LxFG46So"
GID = "52995101"  # the "Roster" tab
URL = f"https://docs.google.com/spreadsheets/d/{SHEET_ID}/export?format=csv&gid={GID}"
COLUMN = "f3 name"
MIN_NAMES = 50     # the roster has ~400 names; far fewer means something changed
MAX_DROP = 0.2     # refuse to lose more than 20% of the names already saved


def fetch(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "rocket-roster-refresh (+https://rocket.f3sactown.com)"})
    with urllib.request.urlopen(req, timeout=60) as res:
        return res.read().decode("utf-8-sig")


def read_names(text: str) -> list:
    reader = csv.DictReader(io.StringIO(text))
    col = next((c for c in reader.fieldnames or [] if c and c.strip().lower() == COLUMN), None)
    if not col:
        sys.exit(f"No 'F3 Name' column in {reader.fieldnames}: the roster sheet layout has changed.")
    names, seen = [], set()
    for r in reader:
        name = re.sub(r"\s+", " ", (r.get(col) or "").replace("‘", "'").replace("’", "'")).strip()
        if name and name.lower() not in seen:
            seen.add(name.lower())
            names.append(name)
    return sorted(names, key=str.lower)


def existing_count(path: Path) -> int:
    if not path.exists():
        return 0
    m = re.search(r"window\.F3_ROSTER = (.*);\s*$", path.read_text(encoding="utf-8"), re.S)
    return len(json.loads(m.group(1))["names"]) if m else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", help="read a CSV export you downloaded instead of downloading it")
    ap.add_argument("--out", default=str(ROOT / "data" / "roster.js"))
    args = ap.parse_args()

    text = Path(args.csv).read_text(encoding="utf-8-sig") if args.csv else fetch(URL)
    names = read_names(text)
    out = Path(args.out)
    before = existing_count(out)
    if len(names) < MIN_NAMES:
        sys.exit(f"Only {len(names)} names found (expected at least {MIN_NAMES}); not writing.")
    if before and len(names) < before * (1 - MAX_DROP):
        sys.exit(f"Name count fell from {before} to {len(names)}; not writing.")

    data = {"source": "F3 SacTown Data sheet, Roster tab", "count": len(names), "names": names}
    out.write_text("// Generated by tools/fetch_roster.py: do not edit by hand.\nwindow.F3_ROSTER = "
                   + json.dumps(data, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
    print(f"Wrote {len(names)} names to {out} (was {before})")


if __name__ == "__main__":
    main()
