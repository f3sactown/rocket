#!/usr/bin/env python3
"""Download recent attendance from the "F3 SacTown Data" Google Sheet into data/attendance.js.

Usage:  python3 tools/fetch_attendance.py [--csv downloaded.csv] [--out data/attendance.js]

The sheet's "Master Data" tab has one row per PAX per workout (Post Date, AO Name,
PAX Name). This keeps, for each AO, the last date each PAX posted there within the
past KEEP_DAYS days. The backblast page uses it to list who has been at the
selected AO in the last 3 months. Names follow the roster's rule: names with
parentheses are left out unless the only one is "(2.0)".

It also keeps each PAX's all-time totals for the home page's "My stats": the
sheet's running "Post Total" and "Q Total" columns (their highest value per PAX),
or, without those columns, the sum of the "Post" and "Q" columns.
Pass --csv to read a CSV you downloaded yourself (File > Download > CSV).

It exits with an error (and writes nothing) if the columns are missing or there
is no recent attendance, so a scheduled run never commits a broken file.
"""
import argparse
import csv
import io
import json
import re
import sys
import urllib.request
from datetime import date, datetime, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fetch_roster import SHEET_ID, keep  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
GID = "0"  # the "Master Data" tab
URL = f"https://docs.google.com/spreadsheets/d/{SHEET_ID}/export?format=csv&gid={GID}"
KEEP_DAYS = 180    # the app shows the last ~3 months; keep extra so a stale file still works
MIN_RECENT = 100   # posts in the kept window; far fewer means something changed


def fetch(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "rocket-attendance-refresh (+https://rocket.f3sactown.com)"})
    with urllib.request.urlopen(req, timeout=120) as res:
        return res.read().decode("utf-8-sig")


def parse_date(raw: str):
    for fmt in ("%m/%d/%Y", "%Y-%m-%d", "%m/%d/%y"):
        try:
            return datetime.strptime(raw.strip(), fmt).date()
        except ValueError:
            pass
    return None


def clean(raw: str) -> str:
    return re.sub(r"\s+", " ", (raw or "").replace("‘", "'").replace("’", "'")).strip()


def build(text: str, today: date) -> tuple:
    reader = csv.DictReader(io.StringIO(text))
    cols = {(c or "").strip().lower(): c for c in reader.fieldnames or []}
    need = ["post date", "ao name", "pax name"]
    if not all(n in cols for n in need):
        sys.exit(f"Unexpected columns {reader.fieldnames}: the Master Data layout has changed.")
    start = today - timedelta(days=KEEP_DAYS)
    aos, posts, totals = {}, 0, {}
    running = "post total" in cols and "q total" in cols

    def num(r, col):
        try:
            return int(float((r.get(cols[col]) or "0").strip() or 0)) if col in cols else 0
        except ValueError:
            return 0

    for r in reader:
        d = parse_date(r.get(cols["post date"]) or "")
        ao, pax = clean(r.get(cols["ao name"])), clean(r.get(cols["pax name"]))
        if d and pax and d <= today:
            t = totals.setdefault(pax, [0, 0])
            if running:
                t[0], t[1] = max(t[0], num(r, "post total")), max(t[1], num(r, "q total"))
            else:
                t[0] += num(r, "post"); t[1] += num(r, "q")
        if not d or not ao or not pax or d < start or d > today or not keep(pax):
            continue
        posts += 1
        last = aos.setdefault(ao, {})
        iso = d.isoformat()
        if last.get(pax, "") < iso:
            last[pax] = iso
    aos = {ao: dict(sorted(v.items(), key=lambda kv: (kv[1], kv[0].lower()), reverse=True)) for ao, v in sorted(aos.items())}
    totals = {k: v for k, v in sorted(totals.items(), key=lambda kv: kv[0].lower()) if v[0] or v[1]}
    return aos, posts, totals


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", help="read a CSV export you downloaded instead of downloading it")
    ap.add_argument("--out", default=str(ROOT / "data" / "attendance.js"))
    ap.add_argument("--today", help="treat this date (YYYY-MM-DD) as today, for testing")
    args = ap.parse_args()

    today = date.fromisoformat(args.today) if args.today else date.today()
    text = Path(args.csv).read_text(encoding="utf-8-sig") if args.csv else fetch(URL)
    aos, posts, totals = build(text, today)
    if posts < MIN_RECENT:
        sys.exit(f"Only {posts} posts in the last {KEEP_DAYS} days (expected at least {MIN_RECENT}); not writing.")

    data = {"source": "F3 SacTown Data sheet, Master Data tab", "builtAt": today.isoformat(), "days": KEEP_DAYS, "aos": aos,
            "totals": totals}
    Path(args.out).write_text("// Generated by tools/fetch_attendance.py: do not edit by hand.\n"
                              "// aos: for each AO, the last date each PAX posted there. totals: each PAX's [posts, Qs].\n"
                              "window.F3_ATTENDANCE = "
                              + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    pairs = sum(len(v) for v in aos.values())
    print(f"Wrote {len(aos)} AOs, {pairs} PAX/AO pairs from {posts} posts, totals for {len(totals)} PAX to {args.out}")


if __name__ == "__main__":
    main()
